-- Migration: plural forms for every countable string (en / es / he).
-- Date: 2026-10-21
-- Purpose:
--   * A "1" must read as a singular everywhere ("1 minute left", not
--     "1 minutes left"). The app resolves the plural form from the CLDR
--     cardinal rules of the content language: see lib/utils/plural_rules.dart
--     and the Edge Function counterpart in
--     supabase/functions/cron-jobs/index.ts.
--   * Convention: the base key holds the plural ("other") form, `<key>_one`
--     the singular and `<key>_two` the Hebrew dual. A locale without a row
--     for the selected form falls back to the base key, so a partially
--     translated locale still renders a sentence.
--   * English fallbacks live in lib/providers/locale_provider.dart.
--
-- DEPLOYMENT: the notifications that carry a count (the match-expiry and
-- pinned-expiry warnings) are written by the cron-jobs edge function, so the
-- function has to be deployed for the new rows to be picked up:
--
--   supabase functions deploy cron-jobs
--
-- The rows already in the notification inbox are repaired by
-- 20262149000000_repair_match_expiry_inbox_plural.sql.

BEGIN;

-- ---------------------------------------------------------------------
-- Drop the rows that the new scheme replaces.
--
-- The singular/plural key pairs ("durationDay" + "durationDays",
-- "matchExtensionDurationHours" + "...HoursPlural", the "{plural}" suffix
-- keys, the "…One"/"…Count" snackbars) are replaced by one key per form.
-- ---------------------------------------------------------------------
