-- Migration: Reactive due-rating-prompt push via pg_cron + Realtime
-- Replaces the client-polling pattern (get_due_match_rating_prompts RPC)
-- with a server-driven push: pg_cron inserts into a small helper table
-- every 5 minutes, and the client subscribes via postgres_changes.

BEGIN;

-- =========================
-- 1) pending_rating_prompts table
-- =========================

CREATE TABLE IF NOT EXISTS public.pending_rating_prompts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  match_id uuid NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
  other_user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  other_name text NOT NULL,
  match_created_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pending_rating_prompts_unique UNIQUE (user_id, match_id)
);

CREATE INDEX IF NOT EXISTS idx_pending_rating_prompts_user_id
  ON public.pending_rating_prompts (user_id);

-- =========================
-- 2) RLS
-- =========================

ALTER TABLE public.pending_rating_prompts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "pending_rating_prompts_select_own"
  ON public.pending_rating_prompts
  FOR SELECT
  TO authenticated
  USING (user_id = auth.uid());

CREATE POLICY "pending_rating_prompts_delete_own"
  ON public.pending_rating_prompts
  FOR DELETE
  TO authenticated
  USING (user_id = auth.uid());

-- INSERT is intentionally not granted to authenticated users (only the
-- SECURITY DEFINER cron function inserts rows).

-- =========================
-- 3) Grant SELECT so Realtime can deliver rows
-- =========================

GRANT SELECT ON TABLE public.pending_rating_prompts TO authenticated;

-- =========================
-- 4) Add to supabase_realtime publication (idempotent)
-- =========================

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'pending_rating_prompts'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.pending_rating_prompts;
    RAISE NOTICE 'public.pending_rating_prompts added to supabase_realtime publication';
  ELSE
    RAISE NOTICE 'public.pending_rating_prompts already in supabase_realtime publication';
  END IF;
END $$;

-- =========================
-- 5) Function: check_all_due_rating_prompts (called by pg_cron)
-- =========================

CREATE OR REPLACE FUNCTION public.check_all_due_rating_prompts(
  p_initial_delay_seconds integer DEFAULT 72000
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  -- 5a) Insert initial prompt rows for matches that don't have one yet and
  --     whose creation time exceeds the initial delay.
  INSERT INTO public.match_rating_prompts (match_id, user_id, next_prompt_at)
  SELECT
    m.id,
    u.id,
    (m.created_at + make_interval(secs => p_initial_delay_seconds))
  FROM public.matches m
  CROSS JOIN LATERAL (VALUES (m.user1_id), (m.user2_id)) AS u(id)
  WHERE NOT EXISTS (
    SELECT 1 FROM public.match_rating_prompts mrp
    WHERE mrp.match_id = m.id AND mrp.user_id = u.id
  )
    AND (m.created_at + make_interval(secs => p_initial_delay_seconds)) <= now()
  ON CONFLICT (match_id, user_id) DO NOTHING;

  -- 5b) Insert pending prompt rows for every due (unrated) prompt that hasn't
  --     already been queued.  ON CONFLICT DO NOTHING keeps this idempotent.
  INSERT INTO public.pending_rating_prompts (user_id, match_id, other_user_id, other_name, match_created_at)
  SELECT
    mrp.user_id,
    mrp.match_id,
    CASE WHEN m.user1_id = mrp.user_id THEN m.user2_id ELSE m.user1_id END,
    public.mask_full_name(u.name),
    m.created_at
  FROM public.match_rating_prompts mrp
  JOIN public.matches m ON m.id = mrp.match_id
  JOIN public.users u
    ON u.id = CASE WHEN m.user1_id = mrp.user_id THEN m.user2_id ELSE m.user1_id END
  WHERE mrp.rating_submitted_at IS NULL
    AND mrp.next_prompt_at IS NOT NULL
    AND mrp.next_prompt_at <= now()
    AND NOT EXISTS (
      SELECT 1 FROM public.pending_rating_prompts prp
      WHERE prp.user_id = mrp.user_id AND prp.match_id = mrp.match_id
    );
END;
$$;

-- =========================
-- 6) pg_cron schedule (every 5 minutes)
-- =========================

CREATE EXTENSION IF NOT EXISTS pg_cron;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    IF NOT EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'check-due-rating-prompts') THEN
      PERFORM cron.schedule(
        'check-due-rating-prompts',
        '*/5 * * * *',
        'SELECT public.check_all_due_rating_prompts()'
      );
    END IF;
  END IF;
END $$;

COMMIT;
